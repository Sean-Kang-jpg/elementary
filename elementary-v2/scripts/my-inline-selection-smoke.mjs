import assert from 'node:assert/strict'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const base = process.argv[2]
if (!base || !['localhost', '127.0.0.1'].includes(new URL(base).hostname)) throw new Error('Use an explicit local URL for fixtures.')
const { chromium } = await import(process.env.CALENDAR_QA_PLAYWRIGHT ? pathToFileURL(process.env.CALENDAR_QA_PLAYWRIGHT).href : 'playwright')
const browser = await chromium.launch({ headless: true, ...(process.env.CALENDAR_QA_CHROME ? { executablePath: process.env.CALENDAR_QA_CHROME } : {}) })
const context = await browser.newContext({ viewport: { width: 390, height: 950 } })
try {
  await context.addInitScript({ path: path.join(root, 'scripts/fixtures/my-schedule-network.js') })
  await context.addInitScript({ path: path.join(root, 'scripts/fixtures/my-schedule-academy-network.js') })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(new URL('/timetable', base).href)
  await page.locator('#timetable-title').waitFor()
  await page.evaluate(() => {
    localStorage.setItem('elementary-favorites-v1', JSON.stringify([{ kind: 'school', id: 'qa-schedule', name: '카드 내 선택 검사용 학교', address: '운영자료 아님', latitude: 0, longitude: 0 }]))
    localStorage.setItem('elementary-schedule-plans-v1', JSON.stringify({ version: 1, activeSchoolId: null, plans: [{ schoolId: 'qa-schedule', schoolName: '카드 내 선택 검사용 학교', entryYear: null, updatedAt: '2026-10-18', entries: [{ id: 'school', label: '정규수업 4교시', kind: 'school', weekdays: [1,2,3,4,5], start: null, end: 780, evidence: 'estimated', participation: 'confirmed', source: { ref: 'qa-school', version: '2026' } }] }] }))
  })
  await page.reload()
  const card = page.locator('.my-add-card')
  const readEntries = () => page.evaluate(() => JSON.parse(localStorage.getItem('elementary-schedule-plans-v1')).plans[0].entries)
  const open = async day => {
    await page.locator('.my-week-nav').getByRole('button', { name: `${day}요일`, exact: true }).click()
    await page.locator('.my-agenda__add').click()
    await card.locator('.my-course-picker[aria-busy=false]').waitFor()
  }
  const art = () => card.locator('[data-program-label="QA 미술 · A"]')
  const care = () => card.locator('.my-course-choice--care').first()
  await open('월')
  assert.equal(await page.locator('.my-program-selection, .my-entry-form').count(), 0)
  assert.equal(await page.locator('.my-entry-list').count(), 1)
  const meta = art().locator('..').locator('.my-course-meta')
  assert.match(await meta.innerText(), /예술 · 월수 · 1~2학년/)
  assert.equal(await meta.evaluate(node => getComputedStyle(node).whiteSpace), 'nowrap')
  assert.equal(await art().count(), 1)
  assert.equal(await card.locator('[data-program-label="QA 미술 · B"]').count(), 0)
  assert.equal(await card.locator('[data-program-label="QA 요일미확인"]').count(), 0)
  await art().click()
  await care().click()
  let entries = await readEntries()
  assert.deepEqual(entries.find(entry => entry.label === 'QA 미술 · A').weekdays, [1])
  assert.deepEqual(entries.find(entry => entry.label === '오후 돌봄').weekdays, [1])
  assert.equal(entries.find(entry => entry.label === 'QA 미술 · A').start, 840)
  assert.equal(entries.find(entry => entry.label === 'QA 미술 · A').participation, 'planned')
  console.log('PASS: card shows Monday courses only and adds only Monday, independently from care, using source times')
  if (process.argv[3]) await card.screenshot({ path: process.argv[3] })
  await open('화')
  assert.equal(await card.locator('[data-program-label]').count(), 0)
  assert.equal(await care().getAttribute('aria-pressed'), 'false')
  await care().click()
  await open('수')
  await art().click()
  await open('월')
  await art().click()
  entries = await readEntries()
  assert.deepEqual(entries.find(entry => entry.label === 'QA 미술 · A').weekdays, [3])
  assert.deepEqual(entries.find(entry => entry.label === '오후 돌봄').weekdays, [1,2])
  console.log('PASS: Tuesday excludes Monday/Friday courses; adding/removing one day preserves Wednesday and other care days')
  await open('목')
  await card.locator('[data-program-label="QA 시간미확인"]').click()
  entries = await readEntries()
  assert.deepEqual([entries.find(entry => entry.label === 'QA 시간미확인').start, entries.find(entry => entry.label === 'QA 시간미확인').end], [null,null])
  console.log('PASS: known weekday with unknown course times remains explicitly unknown')
  await card.getByRole('button', { name: '외부 학원', exact: true }).click()
  assert.match(await card.locator('.my-academy-picker').textContent(), /학교 건물과의 거리는 아니에요/)
  assert.equal(await page.evaluate(() => window.qaAcademyReads), 0)
  await card.getByRole('button', { name: '수학', exact: true }).click()
  await card.locator('.my-academy-results button').first().waitFor()
  assert.match(await card.locator('.my-academy-results').textContent(), /QA 수학학원/)
  assert.doesNotMatch(await card.locator('.my-academy-results').textContent(), /QA 영어학원/)
  assert.match(await card.locator('.my-academy-results').textContent(), /120m/)
  await card.locator('.my-academy-results button').click()
  const form = card.locator('.my-calendar-form')
  assert.equal(await form.getByLabel('시작', { exact: true }).inputValue(), '')
  assert.equal(await form.getByLabel('종료', { exact: true }).inputValue(), '')
  await form.getByLabel('시작', { exact: true }).fill('16:05')
  await form.getByLabel('종료', { exact: true }).fill('16:40')
  await form.getByRole('button', { name: '저장', exact: true }).click()
  await card.waitFor({ state: 'detached' })
  const academy = (await readEntries()).find(entry => entry.label.includes('QA 수학학원'))
  assert.deepEqual([academy.weekdays, academy.start, academy.end, academy.kind, academy.participation, academy.source], [[4],965,1000,'personal','considering',undefined])
  console.log('PASS: topic → nearby individual institution → explicit 5-minute times → editable candidate; no invented academy hours')
  await open('월')
  await card.getByRole('button', { name: '외부 학원', exact: true }).click()
  await page.evaluate(() => { window.qaAcademyFail = true })
  await card.getByRole('button', { name: '영어', exact: true }).click()
  await card.getByRole('button', { name: '학원 다시 불러오기', exact: true }).waitFor()
  await page.evaluate(() => { window.qaAcademyFail = false })
  await card.getByRole('button', { name: '학원 다시 불러오기', exact: true }).click()
  await card.locator('.my-academy-results button').first().waitFor()
  assert.match(await card.locator('.my-academy-results').textContent(), /QA 영어학원/)
  await card.getByRole('button', { name: '코딩', exact: true }).click()
  assert.match(await card.locator('.my-academy-results').textContent(), /조회되지 않았어요/)
  if (process.argv[3]) {
    await card.getByRole('button', { name: '미술·음악·무용', exact: true }).click()
    await card.screenshot({ path: process.argv[3].replace('.png', '-academies.png') })
  }
  await card.getByRole('button', { name: '직접 입력', exact: true }).click()
  await form.getByLabel('일정 이름').fill('저장 실패 검증')
  await page.evaluate(() => { window.qaSetItem = Storage.prototype.setItem; Storage.prototype.setItem = function(key,value) { if (key === 'elementary-schedule-plans-v1') throw Error('QA quota'); return window.qaSetItem.call(this,key,value) } })
  await form.getByRole('button', { name: '저장', exact: true }).click()
  assert.match(await form.getByRole('alert').textContent(), /저장하지 못했어요/)
  assert.equal((await readEntries()).some(entry => entry.label === '저장 실패 검증'), false)
  await page.evaluate(() => { Storage.prototype.setItem = window.qaSetItem })
  await page.keyboard.press('Escape')
  assert.equal(await card.count(), 0)
  for (const width of [360,430,1280]) {
    await page.setViewportSize({ width, height: 1000 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  }
  assert.deepEqual(errors, [])
  console.log('PASS: academy loading/error/retry/empty states, failed storage, Escape and responsive layouts are safe')
} finally { await context.close(); await browser.close() }
